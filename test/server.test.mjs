  const stored=await fs.readFile(path.join(temp,'ai-config.json'),'utf8');assert.ok(!stored.includes('mock-key-for-local-test'));assert.match(stored,/encryptedKey/);
  const ai=await post('preview',{text:'试行年度预算与复核制度'});assert.equal(ai.status,200,JSON.stringify(ai.body));assert.equal(ai.body.plan.source,'ai');assert.equal(ai.body.plan.domain,'finance');
  assert.equal((await post('enact',{id:ai.body.id})).status,200);
  await post('new',{mode:'balanced'});
  const aiParley=await post('preview',{text:'招安反民'});assert.equal(aiParley.status,200);assert.ok(aiParley.body.plan.recruitment);assert.equal(aiParley.body.plan.source,'ai');
  await post('config',{enabled:true,model:'mock-bad',baseUrl:'https://ai-test.invalid'});
  assert.equal((await post('preview',{text:'试行预算'})).status,400);
  boot=await fetch(origin+'/api/bootstrap').then(r=>r.json());assert.equal(boot.state.money,460);
  await post('config',{enabled:true,model:'mock-401',baseUrl:'https://ai-test.invalid'});
  const denied=await post('preview',{text:'试行预算'});assert.match(denied.body.error,/Key/);
  await post('config',{enabled:false,model:'deepseek-flash',baseUrl:'https://api.deepseek.com',clearKey:true});
